import type { AppDefinition } from './types.ts'

/** Install mode reported by the listing. Absent in a definition means `json`. */
export type CatalogInstallMode = 'json' | 'recipe-only'

interface CatalogIndexEntry {
	id: string
	label: string
	catalogVersion: number
	fingerprint: string
	installMode: CatalogInstallMode
	definitionPath: string
	recipePath: string
}

/** Import list, alphabetical by id. The order is the listing order. */
var CATALOG: AppDefinition[] = [
	appStoreDefinition as AppDefinition,
	arrowGameDefinition as AppDefinition,
	calculatorDefinition as AppDefinition,
	calendarDefinition as AppDefinition,
	cellularPlaygroundDefinition as AppDefinition,
	clockDefinition as AppDefinition,
	counterDefinition as AppDefinition,
	dailyFeedDefinition as AppDefinition,
	eightBallDefinition as AppDefinition,
	genericFeedDefinition as AppDefinition,
	hoodieWeatherDefinition as AppDefinition,
	linkDropDefinition as AppDefinition,
	macPuzzleDefinition as AppDefinition,
	newsDefinition as AppDefinition,
	probeDefinition as AppDefinition,
	settingsDefinition as AppDefinition,
	threeBitArtDefinition as AppDefinition,
	xkcdDefinition as AppDefinition,
]

function definitionById(id: string): AppDefinition | null {
	for (var i = 0; i < CATALOG.length; i++) {
		if (CATALOG[i].id === id) return CATALOG[i]
	}
	return null
}

export interface CatalogSummary {
	id: string
	name: string
	label: string
	icon?: string
	category?: string
	description?: string
	/** Install mode from the generated index (a definition without one is `json`). */
	installMode: CatalogInstallMode
}

/**
 * Summaries for the store listing: membership and alphabetical order come
 * from the generated index; the display fields come from the imported
 * definitions. An index entry with no import entry is skipped, so a
 * directory outside the import list is never listed.
 */
export function list_catalog(): CatalogSummary[] {
	var entries = (catalogIndex as { apps: CatalogIndexEntry[] }).apps
	var summaries: CatalogSummary[] = []
	for (var i = 0; i < entries.length; i++) {
		var entry = entries[i]
		var def = definitionById(entry.id)
		if (def === null) continue
		summaries.push({
			id: entry.id,
			name: def.name,
			label: entry.label,
			icon: def.icon,
			category: def.category,
			description: def.description,
			installMode: entry.installMode,
		})
	}
	return summaries
}

/** Full definition for install, or null for an unknown id (no write). */
export function get_catalog_definition(id: string): AppDefinition | null {
	return definitionById(id)
}
