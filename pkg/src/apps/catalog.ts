/**
 * Shipped catalog: each app is a directory under `pkg/catalog/` holding
 * `definition.json` (the installable definition) plus `RECIPE.md` (the
 * install recipe), and the catalog listing is driven by the generated
 * index `pkg/catalog/catalog.json`.
 *
 * The Worker has no directory listing at runtime, so the catalog is still
 * an explicit import list below, alphabetical by id — not discovered by
 * convention. A directory in `pkg/catalog/` without an import entry is NOT
 * listed; the harness in `tests/catalog-harness.ts` fails when the
 * directories, the generated index, and this list disagree.
 *
 * The index is generated by `scripts/build-catalog-index.ts` (repo tooling)
 * and is never hand-written: editing an app or a recipe means re-running
 * the generator. Definitions stay statically imported because install needs
 * the full definition; the index supplies membership, order, and each
 * entry's `installMode`.
 *
 * Catalog definitions are publisher-shipped and trusted like any
 * `add_app` definition: installing one trusts its bundle code, which
 * runs same-origin with session authority. Every catalog definition
 * must validate through `validateDefinition` and install through
 * `add_app` in a blank store (see the harness).
 */

