/**
 * Build the generated icon registry at `pkg/src/icons-registry.ts`.
 *
 * Run with bun from the repo root:
 *
 *   bun scripts/build-icons-registry.ts
 *
 * Compiles all valid `pkg/icons/*.svg` files into a TypeScript map so the shell
 * and client <os-icon> have synchronous access to `kody:*` icons with zero network calls.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

var __dirname = dirname(fileURLToPath(import.meta.url))
var repoRoot = join(__dirname, '..')
var iconsDir = join(repoRoot, 'pkg', 'icons')
var targetFile = join(repoRoot, 'pkg', 'src', 'icons-registry.ts')
var clientTargetFile = join(repoRoot, 'pkg', 'src', 'client', 'icons-data.ts')

var icons: Record<string, string> = {}

if (existsSync(iconsDir)) {
	var files = readdirSync(iconsDir).sort()
	for (var i = 0; i < files.length; i++) {
		var file = files[i]
		if (file.endsWith('.svg')) {
			var name = file.slice(0, -4)
			var content = readFileSync(join(iconsDir, file), 'utf8').trim()
			icons[name] = content
		}
	}
}

var lines: string[] = [
	'/**',
	' * GENERATED from pkg/icons/*.svg — do not hand-edit.',
	' * Source of truth is pkg/icons/. Regenerate after adding or changing icons.',
	' */',
	'export const ICONS: Record<string, string> = ' + JSON.stringify(icons, null, '\t') + ';',
	'',
	'export function getIcon(name: string): string | undefined {',
	'\treturn ICONS[name];',
	'}',
	'',
]

var clientLines: string[] = [
'/**',
' * GENERATED from pkg/icons/*.svg — do not hand-edit.',
' * Client-local mirror of pkg/src/icons-registry.ts for the FE/BE boundary:',
' * os-icon imports only from pkg/src/client/. Regenerated by the same script.',
' * ES2019 only.',
' */',
'export const ICONS: Record<string, string> = ' + JSON.stringify(icons, null, '\t') + ';',
'',
'export function getIcon(name: string): string | undefined {',
'\treturn ICONS[name];',
'}',
'',
]

writeFileSync(targetFile, lines.join('\n'), 'utf8')
writeFileSync(clientTargetFile, clientLines.join('\n'), 'utf8')
console.log('Compiled ' + Object.keys(icons).length + ' icons into ' + targetFile + ' and ' + clientTargetFile)
